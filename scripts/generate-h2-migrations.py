"""Generate the local H2 bootstrap from the canonical MySQL migrations.

H2 keeps relational/unique/status constraints. MySQL JSON_TYPE/JSON_VALID constraints
are verified separately by verify-final-schema.py against MySQL, not emulated here.
"""
from pathlib import Path
import re

ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'apps/api/src/main/resources/db/migration'
TARGET=ROOT/'apps/api/src/main/resources/db/migration-h2'


def without_json_checks(sql):
    while True:
        found=None
        for match in re.finditer(r'CONSTRAINT\s+\w+\s+CHECK\s*\(',sql):
            depth=1; end=match.end(); quoted=False
            while depth:
                char=sql[end]
                if char=="'": quoted=not quoted
                elif not quoted:
                    if char=='(':depth+=1
                    elif char==')':depth-=1
                end+=1
            if re.search(r'JSON_(TYPE|VALID)',sql[match.end():end]):
                start=match.start()
                after=end
                while sql[after:after+1].isspace():after+=1
                if sql[after:after+1]==',':end=after+1
                else:
                    before=start-1
                    while sql[before].isspace():before-=1
                    if sql[before]==',':start=before
                found=(start,end);break
        if not found:return sql
        sql=sql[:found[0]]+sql[found[1]:]


def convert(sql):
    sql=re.sub(r'\bmonth\b', '"month"', sql)
    sql=re.sub(r'(?m)^SET (NAMES|time_zone).*;\s*','',sql)
    sql=re.sub(r'ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci','',sql)
    sql=re.sub(r'CHARACTER SET ascii','',sql)
    sql=re.sub(r'COLLATE (utf8mb4_bin|ascii_bin)','',sql)
    sql=without_json_checks(sql)
    sql=re.sub(r'\bJSON(?=\s+(?:NULL|NOT))','CLOB',sql)
    sql=re.sub(r'\bUNSIGNED\b','',sql)
    sql=re.sub(r'BIGINT\s+NOT NULL AUTO_INCREMENT','BIGINT GENERATED BY DEFAULT AS IDENTITY',sql)
    sql=re.sub(r'BIGINT\s+AUTO_INCREMENT','BIGINT GENERATED BY DEFAULT AS IDENTITY',sql)
    sql=sql.replace('DATETIME(6)','TIMESTAMP(6)').replace('DATETIME','TIMESTAMP')
    sql=sql.replace('UTC_TIMESTAMP(6)','CURRENT_TIMESTAMP(6)')
    sql=sql.replace("CONVERT_TZ(approved_at, '+09:00', '+00:00')", "DATEADD('HOUR', -9, approved_at)")
    sql=sql.replace("CONVERT_TZ(canceled_at, '+09:00', '+00:00')", "DATEADD('HOUR', -9, canceled_at)")
    sql=sql.replace("DATE_FORMAT(CONVERT_TZ(approved_at, '+00:00', '+09:00'), '%Y-%m')", "FORMATDATETIME(DATEADD('HOUR', 9, approved_at), 'yyyy-MM')")
    sql=sql.replace("DATE_FORMAT(DATE_SUB(dc.today, INTERVAL 1 MONTH), '%Y-%m')", "FORMATDATETIME(DATEADD('MONTH', -1, dc.today), 'yyyy-MM')")
    sql=sql.replace("DATE_FORMAT(dc.today, '%Y-%m')", "FORMATDATETIME(dc.today, 'yyyy-MM')")
    sql=sql.replace("JSON_ARRAY('iCloud+', 'Apple Music', '앱 내 구입')", "'[\"iCloud+\",\"Apple Music\",\"앱 내 구입\"]'")
    return '-- GENERATED by scripts/generate-h2-migrations.py; edit db/migration source instead.\n'+sql


TARGET.mkdir(exist_ok=True)
for path in sorted(SOURCE.glob('V*.sql')):
    (TARGET/path.name).write_text(convert(path.read_text()))
    print(TARGET/path.name)
